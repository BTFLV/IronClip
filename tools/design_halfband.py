#!/usr/bin/env python3
"""Design the equiripple half-band FIR filters used by IronClip's oversampler.

Each 2x stage uses a linear-phase half-band filter whose passband edge sits at
0.45 x the *base* sample rate, so the audible band stays flat and every alias
that could fold below that edge is pushed into the stopband.

The filters are designed with the Vaidyanathan/Nguyen trick: an equiripple
type-II prototype g of length 2K is designed with Parks-McClellan, then
interleaved with zeros and given a centre tap of 0.5. The result is an exact
half-band filter of length 4K-1 (every other tap is exactly zero).

Usage:  python3 tools/design_halfband.py > src/dsp/HalfbandCoefficients.h
Requires numpy and scipy (development only).
"""
import sys

import numpy as np
from scipy import signal

# (stage name, passband edge relative to the stage's own sample rate, K)
# Stage 1 runs at 2x, stage 2 at 4x and stage 3 at 8x the base rate.
STAGES = [
    ("Stage1", 0.45 / 2.0, 32),
    ("Stage2", 0.45 / 4.0, 6),
    ("Stage3", 0.45 / 8.0, 4),
]


def design(fp: float, k: int) -> np.ndarray:
    g = signal.remez(2 * k, [0.0, 2.0 * fp, 0.5, 0.5], [1.0, 0.0], weight=[1.0, 1.0], fs=1.0)
    h = np.zeros(4 * k - 1)
    h[0::2] = 0.5 * g
    h[2 * k - 1] = 0.5
    return h


def analyse(h: np.ndarray, fp: float):
    w, H = signal.freqz(h, worN=1 << 16, fs=1.0)
    mag = np.abs(H)
    passband = mag[w <= fp]
    stopband = mag[w >= 0.5 - fp]
    ripple_db = 20.0 * np.log10(np.max(np.abs(passband - 1.0)) + 1.0)
    atten_db = -20.0 * np.log10(np.max(stopband))
    return ripple_db, atten_db


def main() -> int:
    out = sys.stdout
    out.write("// Generated by tools/design_halfband.py. Do not edit by hand.\n")
    out.write("//\n// Linear-phase half-band FIR filters for the 2x/4x/8x oversampler.\n")
    out.write("// Only the non-zero odd-offset taps of one symmetric half are stored;\n")
    out.write("// the centre tap of every half-band filter is exactly 0.5.\n\n")
    out.write("#pragma once\n\nnamespace ironclip::dsp::halfband\n{\n")
    for name, fp, k in STAGES:
        h = design(fp, k)
        ripple, atten = analyse(h, fp)
        centre = 2 * k - 1
        # taps at offsets 1, 3, 5, ... from the centre (symmetric)
        half = [h[centre + 1 + 2 * i] for i in range(k)]
        out.write(f"\n// {name}: {len(h)} taps, passband edge {fp:.5f} fs, "
                  f"stopband from {0.5 - fp:.5f} fs,\n")
        out.write(f"// passband ripple {ripple:.6f} dB, stopband attenuation {atten:.1f} dB\n")
        out.write(f"struct {name}\n{{\n  static constexpr int kNumTaps = {len(h)};\n")
        out.write(f"  static constexpr int kHalfOdd = {k};\n")
        out.write(f"  static constexpr double kTaps[{k}] = {{\n")
        for i, c in enumerate(half):
            sep = "," if i < k - 1 else ""
            out.write(f"    {c:+.17e}{sep}\n")
        out.write("  };\n};\n")
        print(f"{name}: N={len(h)} ripple={ripple:.6f} dB atten={atten:.1f} dB", file=sys.stderr)
    out.write("\n} // namespace ironclip::dsp::halfband\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
